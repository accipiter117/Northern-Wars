// Writes sw.js: the service worker that keeps every game file in a versioned
// cache, so the game starts at once and plays offline. The version is a hash
// of the files, so any change makes a new cache and the game offers a
// restart. Run after changing any game file: npm run sw (a test checks it).
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const TOP = ['index.html', 'styles.css', 'manifest.webmanifest'];
const DIRS = ['src', 'data', 'icons'];

async function walk(dir) {
  const out = [];
  for (const e of await readdir(join(ROOT, dir), { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isDirectory()) out.push(...await walk(p));
    else out.push(p);
  }
  return out;
}

export async function swSource() {
  const files = [...TOP, ...(await Promise.all(DIRS.map(walk))).flat()].map((f) => relative(ROOT, join(ROOT, f)).split('\\').join('/')).sort();
  const hash = createHash('sha256');
  for (const f of files) hash.update(f).update(await readFile(join(ROOT, f)));
  const version = hash.digest('hex').slice(0, 12);
  return `// Generated by tools/sw.mjs (npm run sw): do not edit by hand.
// Every game file is kept in a versioned cache. Pages load from the cache
// first, so the game starts at once and plays offline; a new version
// installs beside the old and waits until the player chooses to restart.
const VERSION = '${version}';
const CACHE = \`northern-wars-\${VERSION}\`;
const FILES = ${JSON.stringify(['./', ...files], null, 2)};

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)));
});

self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith('northern-wars-') && k !== CACHE).map((k) => caches.delete(k))))
    .then(() => self.clients.claim()));
});

self.addEventListener('message', (e) => {
  if (e.data === 'restart') self.skipWaiting();
});

// Music is not part of the install (it is large); it is kept in its own
// cache after the first full download, and served from there with proper
// Range answers, which Safari needs to play cached media at all.
const AUDIO = 'nw-audio-v1';
async function audio(req) {
  const key = req.url.split('?')[0].split('#')[0];
  const cache = await caches.open(AUDIO);
  let full = await cache.match(key);
  if (!full) {
    try {
      const res = await fetch(key);
      if (res.status !== 200) return res;
      await cache.put(key, res.clone());
      full = res;
    } catch {
      return new Response('', { status: 504 });
    }
  }
  const range = req.headers.get('range');
  if (!range) return full;
  const buf = await full.clone().arrayBuffer();
  const size = buf.byteLength;
  const m = /bytes=(\\d*)-(\\d*)/.exec(range);
  let start = 0;
  let end = size - 1;
  if (m && m[1] === '' && m[2] !== '') start = Math.max(0, size - Number(m[2]));
  else if (m) {
    start = Number(m[1] || 0);
    if (m[2] !== '') end = Math.min(size - 1, Number(m[2]));
  }
  if (start >= size || start > end) return new Response('', { status: 416, headers: { 'Content-Range': \`bytes */\${size}\` } });
  return new Response(buf.slice(start, end + 1), {
    status: 206,
    headers: {
      'Content-Type': full.headers.get('Content-Type') || 'audio/mp4',
      'Content-Range': \`bytes \${start}-\${end}/\${size}\`,
      'Content-Length': String(end - start + 1),
      'Accept-Ranges': 'bytes',
    },
  });
}

self.addEventListener('fetch', (e) => {
  const url = new URL(e.request.url);
  if (e.request.method !== 'GET' || url.origin !== self.location.origin) return;
  if (url.pathname.includes('/assets/audio/')) {
    e.respondWith(audio(e.request));
    return;
  }
  // The page itself is found whatever its query (?seed=, ?paused).
  e.respondWith(caches.open(CACHE).then((c) => c.match(e.request, { ignoreSearch: true })
    .then((hit) => hit ?? fetch(e.request))));
});
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await writeFile(join(ROOT, 'sw.js'), await swSource());
  console.log('sw.js written');
}
